let registered = false;

/** Rejestruje nakładkę raz na sesję - `i18n.exists()` bez niej zwraca fałsz. */
export function ensureEventRegistrationI18n(): void {
  if (registered) return;
  i18n.addResourceBundle("pl", "translation", eventRegistrationPl, true, true);
  i18n.addResourceBundle("en", "translation", eventRegistrationEn, true, true);
  registered = true;
}
