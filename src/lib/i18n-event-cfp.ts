// Rejestracja przy imporcie + idempotentne `ensure…` (umowa z `i18n-event-meetings`):
// parytet czyta zasoby po imporcie, a mapa błędów pyta `i18n.exists()` przed
// pierwszym renderem.
let registered = false;
export function ensureEventCfpI18n(): void {
  if (registered) return;
  registered = true;
  i18n.addResourceBundle("pl", "translation", eventCfpPl, true, true);
  i18n.addResourceBundle("en", "translation", eventCfpEn, true, true);
}
ensureEventCfpI18n();
