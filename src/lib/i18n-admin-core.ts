// Rejestracja przy imporcie (wymóg bramki integralności) + idempotentne
// `ensureI18n()` jako kotwica, która trzyma import w chunku `AdminSession`.
// overwrite=true: kopie tych samych zdań w nakładkach ekranów
// (`i18n-admin-media`, `i18n-admin-users`…) mogą zarejestrować się wcześniej,
// a właścicielem napisu jest ten plik - jak dotąd rdzeń.
let registered = false;
export function ensureI18n(): void {
  if (registered) return;
  registered = true;
  i18n.addResourceBundle("pl", "translation", adminCorePl, true, true);
  i18n.addResourceBundle("en", "translation", adminCoreEn, true, true);
}
ensureI18n();
